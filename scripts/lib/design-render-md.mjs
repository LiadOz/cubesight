import { FRAME_IDS, r2, r3 } from './design-analyse.mjs';

const md = (rows) => rows.join('\n');
const esc = (s) => String(s).replace(/\|/g, '\\|');
function table(head, rows) {
  return md([`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.map((c) => esc(c ?? '')).join(' | ')} |`)]);
}
const q = (s) => `\`${s}\``;
const list = (xs) => xs.join(', ');
const short = (id) => id.replace(/^(A-\d+b?)-.*/, '$1');

