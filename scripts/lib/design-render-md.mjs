function geom(e) {
  if (e.k === 'text') return `x ${r2(e.x)}, y ${r2(e.y)} (baseline), anchor ${e.anchor}`;
  if (e.k === 'rect') return `x ${r2(e.x)}, y ${r2(e.y)}, ${r2(e.width)} x ${r2(e.height)}, rx ${e.rx}`;
  if (e.k === 'circle') return `c (${r2(e.cx)}, ${r2(e.cy)}) r ${e.r}`;
  if (e.k === 'line') return `(${r2(e.x1)}, ${r2(e.y1)}) -> (${r2(e.x2)}, ${r2(e.y2)})`;
  if (e.k === 'ellipse') return `c (${r2(e.cx)}, ${r2(e.cy)}) rx ${e.rx} ry ${e.ry}`;
  return JSON.stringify(e);
}
function paint(e, tk) {
  if (e.k === 'text') return `${e.style}; "${e.text}"${e.groupOpacity !== undefined ? `; group opacity ${e.groupOpacity}` : ''}`;
  const bits = [];
  if (e.fill) bits.push(`fill ${tk(e.fill)}`);
  if (e.stroke) bits.push(`stroke ${tk(e.stroke)}${e.strokeWidth ? ` ${e.strokeWidth}` : ''}`);
  if (e.opacity) bits.push(`opacity ${e.opacity}`);
  if (e.strokeLinecap) bits.push(e.strokeLinecap);
  return bits.join(', ');
}

function fmt(e, tk, styles) {
  const off = e.offset && (e.offset[0] || e.offset[1]) ? `[dev ${e.offset.join(',')}] ` : '';
  const g = e.groupOpacity !== undefined ? ` group-opacity ${e.groupOpacity}` : '';
  if (e.k === 'text') {
    const st = styles[e.style];
    return `${off}text "${e.text}" ${e.style} ${st.family}${st.size}/${st.weight} ${st.fillToken}${st.letterSpacing !== null ? ` ls${st.letterSpacing}` : ''} (${r2(e.x)}, ${r2(e.y)}) ${e.anchor}${e.opacity !== undefined ? ` opacity ${e.opacity}` : ''}${g}`;
  }
  if (e.k === 'sparkle') return `${off}sparkle (${e.x}, ${e.y}) arm ${e.arm} ${paint(e, tk)}`;
  if (e.k === 'path') return `${off}path ${e.d} ${paint(e, tk)}`;
  return `${off}${e.k} ${geom(e)} ${paint(e, tk)}${g}`;
}

const keyFns = {
  text: (e) => `t|${e.text}`,
  rect: (e) => `r|${e.x}|${e.y}`,
  circle: (e) => `c|${e.cx}|${e.cy}`,
  line: (e) => `l|${e.x1}|${e.y1}`,
  ellipse: (e) => `e|${e.cx}|${e.cy}`,
  sparkle: (e) => `s|${e.x}|${e.y}`,
  path: (e) => `p|${e.d}`,
};

let sdesc = (v) => v;
function delta(ref, now) {
  const sigOf = (e) => JSON.stringify(e);
  const remaining = ref.map((e) => ({ e, used: false }));
  const added = [];
  const unmatched = [];
  let same = 0;
  for (const e of now) {
    const hit = remaining.find((r) => !r.used && sigOf(r.e) === sigOf(e));
    if (hit) { hit.used = true; same++; } else unmatched.push(e);
  }
  const changed = [];
  for (const e of unmatched) {
    const k = keyFns[e.k](e);
    const hit = remaining.find((r) => !r.used && r.e.k === e.k && keyFns[r.e.k](r.e) === k);
    if (hit) {
      hit.used = true;
      const diffsRaw = [...new Set([...Object.keys(e), ...Object.keys(hit.e)])].filter((key) => JSON.stringify(e[key]) !== JSON.stringify(hit.e[key]));
      const show = (key, v) => (key === 'style' && v ? sdesc(v) : JSON.stringify(v) ?? 'none');
      const diffs = diffsRaw.map((key) => `${key} ${show(key, hit.e[key])} -> ${show(key, e[key])}`).join('; ');
      changed.push({ now: e, was: hit.e, diffs, diffsRaw });
    } else added.push(e);
  }
  const removed = remaining.filter((r) => !r.used).map((r) => r.e);
  return { same, changed, added, removed };
}

function cubeSummary(cb, faces) {
  const names = {};
  for (const [fam, v] of Object.entries(faces)) { names[v.top] = fam; names[v.left] = fam; names[v.right] = fam; }
  const byFace = {};
  for (const s of cb.stickers) (byFace[s.face] ??= []).push(`${names[s.fill] ?? (s.fill === '#2a2d33' ? 'unknown' : s.fill)}${s.cls ? `*${s.cls}` : ''}`);
  const comp = (xs) => { const m = new Map(); xs.forEach((x) => m.set(x, (m.get(x) ?? 0) + 1)); return [...m].map(([k, v]) => `${v} ${k}`).join(' + '); };
  return `top ${comp(byFace.top)}; left ${comp(byFace.left)}; right ${comp(byFace.right)}${cb.stickers.some((s) => s.cls) ? ' (*hl = highlight class on that sticker)' : ''}`;
}

