function bb(c) { return `${c.bbox.x}, ${c.bbox.y}, ${c.bbox.w}, ${c.bbox.h}`; }

function faceVerts(cu) {
  const polys = cu.stickers;
  const hex = cu.hexagon.vertices;
  const fmt = (p) => p.map((v) => `(${v[0]}, ${v[1]})`).join(' ');
  const rows = [`hexagon  ${fmt(hex)}`];
  for (const face of ['top', 'left', 'right']) {
    const f = polys.filter((s) => s.face === face);
    rows.push(`${face} face, ${f.length} stickers; first: ${fmt(f[0].points)}; last: ${fmt(f[f.length - 1].points)}`);
  }
  return rows;
}

function roleCounts(segs) {
  const m = new Map();
  for (const s of segs) m.set(s.role + (s.overlay ? ' (overlay)' : ''), (m.get(s.role + (s.overlay ? ' (overlay)' : '')) ?? 0) + 1);
  return [...m].map(([k, v]) => `${v}x ${k}`).join(', ');
}

function gapRange(r) {
  const gs = r.gaps.slice(0, -1).map((g) => g.spanDeg);
  if (!gs.length) return 'no gaps';
  const lo = Math.min(...gs);
  const hi = Math.max(...gs);
  return `segment gap ${lo === hi ? lo : `${lo} to ${hi}`} deg, closing gap ${r.gaps[r.gaps.length - 1].spanDeg} deg`;
}

function ringTable(r, tk) {
  const rows = [];
  let n = 0;
  r.segments.forEach((s) => {
    const idx = s.overlay ? 'overlay' : String(n++);
    const gapAfter = !s.overlay ? r.gaps[n - 1] : null;
    rows.push([idx, s.startDeg, s.endDeg, s.spanDeg, `${tk(s.stroke)}`, s.strokeWidth, s.opacity ?? '', s.role, gapAfter ? `${gapAfter.spanDeg}` : '']);
  });
  return `Ring r${r.r}, centre (${r.centre.join(', ')})${r.offset[0] || r.offset[1] ? ` + device (${r.offset.join(', ')})` : ''}, ${r.segments.filter((s) => !s.overlay).length} base segments:\n\n` +
    table(['#', 'start deg', 'end deg', 'span', 'stroke', 'width', 'opacity', 'role', 'gap after'], rows);
}

function labelTable(p) {
  return table(['text', 'anchor', 'angle', 'radius to anchor', 'radius to glyph centre', 'side of ring', 'nearest segment', 'segment mid', 'offset'],
    p.labels.map((l) => [l.text, l.anchor, l.angleDeg, l.radius, l.radiusCentred, l.radiusCentred > p.ring + 0.5 ? `outside +${r2(l.radiusCentred - p.ring)}` : l.radiusCentred < p.ring - 0.5 ? `inside ${r2(l.radiusCentred - p.ring)}` : 'on ring', l.segment, l.segmentMidDeg, l.offsetDeg]));
}

function dedupeRows(rows) {
  const seen = new Map();
  for (const r of rows) {
    const k = [r[0], r[2], r[3], r[4]].join('|');
    const e = seen.get(k);
    if (e) e[1] += ` + ${r[1]}`; else seen.set(k, [...r]);
  }
  return [...seen.values()];
}

function compact(e) {
  const off = e.offset && (e.offset[0] || e.offset[1]) ? `[dev ${e.offset.join(',')}] ` : '';
  if (e.k === 'text') return `${off}"${e.text}" ${e.style} @(${r2(e.x)}, ${r2(e.y)})`;
  if (e.k === 'rect') return `${off}rect @(${r2(e.x)}, ${r2(e.y)}) ${r2(e.width)}x${r2(e.height)}`;
  if (e.k === 'circle') return `${off}circle @(${r2(e.cx)}, ${r2(e.cy)}) r${e.r}`;
  if (e.k === 'line') return `${off}line (${r2(e.x1)}, ${r2(e.y1)})->(${r2(e.x2)}, ${r2(e.y2)})`;
  if (e.k === 'ellipse') return `${off}ellipse @(${r2(e.cx)}, ${r2(e.cy)})`;
  return `${off}${e.k}`;
}

function ringDiff(prev, r) {
  const rows = [];
  const pb = prev.segments.filter((x) => !x.overlay);
  r.segments.filter((x) => !x.overlay).forEach((seg, i) => {
    const o = pb[i];
    if (!o || o.stroke !== seg.stroke || o.strokeWidth !== seg.strokeWidth || Math.abs(o.startDeg - seg.startDeg) > 0.02 || Math.abs(o.endDeg - seg.endDeg) > 0.02) rows.push([i, `${o?.startDeg} -> ${o?.endDeg}`, `${seg.startDeg} -> ${seg.endDeg}`, `${o?.role}`, `${seg.role}`, `${seg.stroke} ${seg.strokeWidth}`]);
  });
  return `Ring vs A-02 (angles identical except where listed): ${rows.length} segment(s) differ.\n\n` + table(['#', 'A-02 span', 'this span', 'A-02 role', 'role', 'stroke width'], rows);
}

function isInner(frame, r) { return frame.rings.some((o) => o.r > r.r && o.centre[0] === r.centre[0] && o.centre[1] === r.centre[1] && o.offset[0] === r.offset[0]); }

