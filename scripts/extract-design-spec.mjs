#!/usr/bin/env node
// Regenerates the exact design spec from the direction-A SVG frames:
//   src/ui/design-spec.js                       (plain-data constants)
//   docs/design/orbit-v3/SPEC-A-EXACT.md        (human-readable spec)
// Usage: node scripts/extract-design-spec.mjs          write both files
//        node scripts/extract-design-spec.mjs --check  exit 1 when a committed file is stale
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSpec } from './lib/design-build.mjs';
import { literal } from './lib/design-serialize.mjs';
import { renderMd } from './lib/design-render-md.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SVG_DIR = path.join(ROOT, 'docs/design/orbit-v3');
export const JS_PATH = path.join(ROOT, 'src/ui/design-spec.js');
export const MD_PATH = path.join(SVG_DIR, 'SPEC-A-EXACT.md');

const EXPORTS = ['CANVAS', 'COLORS', 'TYPE', 'ORBIT', 'CUBE', 'ANCHORS', 'FRAMES'];

export function renderJs(spec) {
  const head = `// GENERATED by scripts/extract-design-spec.mjs from docs/design/orbit-v3/A-*.svg. Do not edit.
// Plain data only: no logic, no DOM. Re-run \`node scripts/extract-design-spec.mjs\` after a frame changes;
// tests/design-spec-unit.test.mjs fails when this file drifts from the SVGs.
// Angles: degrees, 0 = 12 o'clock, clockwise positive. Lengths: SVG user units of the frame
// (desktop frames 1440x900; phone coordinates are local to a 390x844 device, see CANVAS.phoneSheet).
`;
  return head + EXPORTS.map((k) => `\nexport const ${k} = ${literal(spec[k])};\n`).join('');
}

export function generate() {
  const spec = buildSpec(SVG_DIR);
  return { js: renderJs(spec), md: renderMd(spec) };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { js, md } = generate();
  if (process.argv.includes('--check')) {
    const stale = [[JS_PATH, js], [MD_PATH, md]].filter(([p, c]) => !fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== c);
    if (stale.length) {
      console.error(`stale: ${stale.map(([p]) => path.relative(ROOT, p)).join(', ')} (run node scripts/extract-design-spec.mjs)`);
      process.exit(1);
    }
    console.log('design spec is up to date');
  } else {
    fs.writeFileSync(JS_PATH, js);
    fs.writeFileSync(MD_PATH, md);
    console.log(`wrote ${path.relative(ROOT, JS_PATH)} (${js.length} bytes) and ${path.relative(ROOT, MD_PATH)} (${md.length} bytes)`);
  }
}
