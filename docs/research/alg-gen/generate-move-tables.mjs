// Generate compact primitive move tables from the official cubing.js 3x3x3
// KPuzzle definition. The checked-in runtime model has no cubing.js dependency.
// The generated values are facts (piece permutations/orientations); test
// verification replays generated algorithms independently through cubing.js.
import fs from 'node:fs';
import { cube3x3x3 } from 'cubing/puzzles';
const kp = await cube3x3x3.kpuzzle();
const N = 46;
function fromTransformation(t) {
  const s = new Uint8Array(N), d = t.transformationData;
  for (let i = 0; i < 8; i++) { s[i] = d.CORNERS.permutation[i]; s[26 + i] = d.CORNERS.orientationDelta[i]; }
  for (let i = 0; i < 12; i++) { s[8 + i] = 8 + d.EDGES.permutation[i]; s[34 + i] = d.EDGES.orientationDelta[i]; }
  for (let i = 0; i < 6; i++) s[20 + i] = 20 + d.CENTERS.permutation[i];
  return [...s];
}
const moves = {};
for (const face of 'URFDLB') for (const suffix of ['', "'", '2']) {
  const name = face + suffix;
  moves[name] = fromTransformation(kp.algToTransformation(name));
}
const out = `// Generated by docs/research/alg-gen/generate-move-tables.mjs from cubing.js ${JSON.parse(fs.readFileSync('node_modules/cubing/package.json')).version} 3x3x3 KPuzzle definition.\n// Source license: cubing.js MPL-2.0 OR GPL-3.0-or-later.\n// Primitive outer-turn transformation data only; see generator for reproducibility.\nexport const MOVE_TABLES = Object.freeze(${JSON.stringify(moves)});\n`;
fs.writeFileSync(new URL('../../../src/analysis/cube-move-tables.js', import.meta.url), out);
